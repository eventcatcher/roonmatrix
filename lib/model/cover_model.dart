class CoverModel {
  String hash;
  String controlId;
  String coverUrl;
  String zoneName;
  String artist;
  String album;
  String track;
  String status;

  CoverModel({
    required this.hash,
    required this.controlId,
    required this.coverUrl,
    required this.zoneName,
    required this.artist,
    required this.album,
    required this.track,
    required this.status,
  });
}
